#!/usr/bin/env node
/* Generate a new FTH key set (run outside the web root's reach, from the repo root):

     node tools/fth-keygen.mjs <output dir, NOT under /var/www> [passphrase]

   Writes <dir>/fth-<keyId>.fthkey (both private keys, encrypted with the passphrase) and
   data/fth-keys.js (public keys, published with the site). Without a passphrase argument a
   random one is generated and written to <dir>/fth-<keyId>.passphrase.txt (mode 600).
   The workspace (/workspace) can do the same in the browser ("New key set").
   After a rotation, packages sealed to the old key can only be opened with the old key file:
   keep it. */
import fs from 'node:fs';
import path from 'node:path';
import { webcrypto } from 'node:crypto';
globalThis.crypto ??= webcrypto;
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const [dir, given] = process.argv.slice(2);
if (!dir) { console.error('usage: node tools/fth-keygen.mjs <output dir> [passphrase]'); process.exit(2); }
const out = path.resolve(dir);
if (out.startsWith('/var/www')) { console.error('refusing to write a private key under /var/www'); process.exit(2); }
await import(path.join(ROOT, 'js/fth/vault.js'));
const V = globalThis.FTHVault;
const pass = given || [V.passphrase(), V.passphrase()].join('-');
const { keyFile, publicKeys } = await V.generateKeySet(pass);
fs.mkdirSync(out, { recursive: true, mode: 0o700 });
const base = path.join(out, 'fth-' + publicKeys.keyId);
fs.writeFileSync(base + '.fthkey', JSON.stringify(keyFile, null, 1), { mode: 0o600 });
if (!given) fs.writeFileSync(base + '.passphrase.txt', pass + '\n', { mode: 0o600 });
fs.writeFileSync(path.join(ROOT, 'data/fth-keys.js'),
  '/* FTH public keys (encryption ECDH P-384, signature ECDSA P-256). Generated by tools/fth-keygen.mjs or the\n' +
  '   workspace "New key set". Private keys are never on this server. Bump ?v= in the pages after a change. */\n' +
  'window.FTH_KEYS = ' + JSON.stringify(publicKeys) + ';\n');
console.log('key id', publicKeys.keyId);
console.log('key file', base + '.fthkey');
if (!given) console.log('passphrase file', base + '.passphrase.txt');
