const acc = {};
const get = (c) => acc[c] ??= { o: opening[c] || 0, d: 0, k: 0 };
Object.keys(opening).forEach(get);
for (const [dr, cr, v] of P) { get(dr).d += v; get(cr).k += v; }
const rows = Object.keys(acc).sort().map((c) => {
  const a = acc[c], close = a.o + a.d - a.k;
  return [c, a.o > 0 ? a.o : 0, a.o < 0 ? -a.o : 0, a.d, a.k, close > 0 ? close : 0, close < 0 ? -close : 0];
});
